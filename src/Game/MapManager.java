    public MapManager(int[][] map) {
        Color colorWals = Color.white;
        Color colorTun = Color.white;
        if( map == map1) {
            colorWals = new Color(0x2a6747);
            colorTun = new Color(0x249898);
        }
        if( map == map2) {
            colorWals = new Color(0x250902);
            colorTun = new Color(0x83220a);
        }
        if( map == map3) {
            colorWals = new Color(0x270101);
            colorTun = new Color(0x460000);
        }
        if( map == map4) {
            colorWals = new Color(0x2d2828);
            colorTun = new Color(0xcecac8);
        }
        if( map == map5) {
            colorWals = new Color(0x353533);
            colorTun = new Color(0x83857f);
        }
        setLayout(new GridBagLayout());
        setBackground(Color.black);
        GridBagConstraints gbc = new GridBagConstraints();
        gbc.fill = GridBagConstraints.BOTH;

        panelGrid = new JPanel[map.length][map[0].length];

        for (int y = 0; y < map.length; y++) {
            for (int x = 0; x < map[y].length; x++) {
                JPanel cellPanel = new JPanel();
                cellPanel.setPreferredSize(new Dimension(cellSize, cellSize));
                cellPanel.setBackground(map[y][x] == 1 ? colorWals : colorTun);
                gbc.gridx = x;
                gbc.gridy = y;
                add(cellPanel, gbc);
                panelGrid[y][x] = cellPanel; // Сохраняем панель в таблицу

                if (map[y][x] == 1) {
                    System.out.println("Wall at: (" + y + ", " + x + ")");
                }
            }
        }
    }

    public static JPanel createMapPanel(int[][] map) {
        return new MapManager(map);
    }

    public static JPanel[][] getPanelGrid() {
        return panelGrid;
    }
